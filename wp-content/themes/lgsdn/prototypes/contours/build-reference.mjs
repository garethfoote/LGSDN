// Run with node to regenerate the radial centre lines from the homepage artwork.
import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../../assets/images/hero-graphic-mark.svg', import.meta.url), 'utf8');
const centre = [110.5, 112];
const count = 512;
function flatten(d) {
  const tokens = d.match(/[MCLHVZ]|-?(?:\d*\.)?\d+(?:e[-+]?\d+)?/gi);
  const segments = [];
  let index = 0, command, x = 0, y = 0, startX, startY;
  const number = () => Number(tokens[index++]);
  const line = (nx, ny) => { segments.push([x, y, nx, ny]); x = nx; y = ny; };
  while (index < tokens.length) {
    if (/^[A-Z]$/.test(tokens[index])) command = tokens[index++];
    if (command === 'M') { x = number(); y = number(); startX = x; startY = y; command = 'L'; }
    else if (command === 'L') line(number(), number());
    else if (command === 'H') line(number(), y);
    else if (command === 'V') line(x, number());
    else if (command === 'Z') { line(startX, startY); command = null; }
    else if (command === 'C') {
      const [x0, y0, x1, y1, x2, y2, x3, y3] = [x, y, number(), number(), number(), number(), number(), number()];
      for (let step = 1; step <= 12; step++) {
        const t = step / 12, u = 1 - t;
        line(u*u*u*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x3,
          u*u*u*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y3);
      }
    } else throw new Error(`Unsupported SVG command ${command}`);
  }
  return segments;
}
const radii = [], widths = [];
for (const match of source.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)) {
  const segments = flatten(match[1]);
  const ring = [], thickness = [];
  for (let sample = 0; sample < count; sample++) {
    const angle = sample / count * Math.PI * 2, dx = Math.cos(angle), dy = Math.sin(angle);
    const hits = [];
    for (const [x1,y1,x2,y2] of segments) {
      const ax = x1-centre[0], ay = y1-centre[1], sx = x2-x1, sy = y2-y1;
      const denominator = dx*sy-dy*sx;
      if (Math.abs(denominator) < 1e-10) continue;
      const distance = (ax*sy-ay*sx)/denominator;
      const along = (ax*dy-ay*dx)/denominator;
      if (distance > 0 && along >= 0 && along < 1) hits.push(distance);
    }
    hits.sort((a,b) => a-b);
    if (hits.length !== 2) throw new Error(`Artwork is not radial: ring ${radii.length}, sample ${sample}, ${hits.length} intersections`);
    ring.push(Number(((hits[0]+hits[1])/2).toFixed(5)));
    thickness.push(hits[1]-hits[0]);
  }
  // A ray measures oblique thickness; project onto the local curve normal.
  const normalWidths = ring.map((radius,i) => {
    const derivative = (ring[(i+1)%count]-ring[(i+count-1)%count])/(4*Math.PI/count);
    return thickness[i]*radius/Math.hypot(radius, derivative);
  }).sort((a,b) => a-b);
  widths.push(Number(normalWidths[count/2].toFixed(4)));
  radii.push(ring);
}
writeFileSync(new URL('../../assets/js/hero-contour-reference.js', import.meta.url), `// Generated by build-reference.mjs from hero-graphic-mark.svg. Do not hand edit.\nexport const reference = ${JSON.stringify({centre, radii, widths})};\n`);
console.log(JSON.stringify({rings:radii.length, samples:count, widths}));
